writeGenerated("packages/protocol/src/provider-ids.generated.ts", protocolTs);

// --- protocol JSON Schemas ---
if (checkOnly) {
  assertSchemaContainsEnum("packages/protocol/schema/quota-snapshot.json", networkIds);
  assertSchemaContainsEnum("packages/protocol/schema/quota-collection-report.json", ids);
} else {
  const result = spawnSync(
    process.execPath,
    [
      "--experimental-strip-types",
      join(root, "packages/protocol/scripts/generate-json-schemas.ts"),
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.error || result.status !== 0) {
    throw new Error(
      `Could not generate protocol schemas: ${result.error?.message ?? result.stderr ?? result.status}`,
    );
  }
  process.stdout.write(result.stdout);
}

// --- Rust ---
const rustVariants = entries
  .map((entry) => `  #[serde(rename = ${rustString(entry.id)})]\n  ${rustIdent(entry.id)},`)
  .join("\n");
const rustMetadata = entries
  .map((entry) => {
    const config = entry.credential_config;
    const configLiteral = config
      ? `Some(ApiKeyConfig { supports_base_url: ${config.supports_base_url}, requires_base_url: ${config.requires_base_url}, allow_private_http: ${config.allow_private_http}, mask_label: ${rustString(config.mask_label)} })`
      : "None";
    const envs = entry.environment_keys.map(rustString).join(", ");
    const browserSession = entry.browser_session
      ? `Some(BrowserSessionConfig { login_url: ${rustString(entry.browser_session.login_url)}, cookie_hosts: &[${entry.browser_session.cookie_hosts.map(rustString).join(", ")}], cookie_names: &[${entry.browser_session.cookie_names.map(rustString).join(", ")}], browser_priority: &[${entry.browser_session.browser_priority.map(rustString).join(", ")}], exclusive: ${entry.browser_session.exclusive} })`
      : "None";
    const defaultBase =
      entry.default_base_url === null ? "None" : `Some(${rustString(entry.default_base_url)})`;
    const baseEnv =
      entry.base_url_environment_key === null
        ? "None"
        : `Some(${rustString(entry.base_url_environment_key)})`;
    return `  ProviderCatalogEntry {
    id: ProviderId::${rustIdent(entry.id)},
    display_name: ${rustString(entry.display_name)},
    order: ${entry.order},
    default_visible: ${entry.default_visible},
    setup_action: ${rustString(entry.setup_action)},
    brand_icon_asset: ${rustString(entry.brand_icon_asset)},
    account_sync: ${entry.account_sync},
    environment_keys: &[${envs}],
    credential_config: ${configLiteral},
    browser_session: ${browserSession},
    default_base_url: ${defaultBase},
    base_url_environment_key: ${baseEnv},
  },`;
  })
  .join("\n");
