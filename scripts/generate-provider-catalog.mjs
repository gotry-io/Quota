function writeGenerated(relative, contents) {
  const path = join(root, relative);
  if (checkOnly) {
    if (readFileSync(path, "utf8") !== contents) {
      throw new Error(`Generated file is out of date: ${relative}`);
    }
    console.log(`${relative} is current`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
  console.log(`wrote ${relative}`);
}

function assertSchemaContainsEnum(relative, expected) {
  const schema = JSON.parse(readFileSync(join(root, relative), "utf8"));
  if (!containsExactEnum(schema, expected)) {
    throw new Error(`Generated provider enum is out of date: ${relative}`);
  }
  console.log(`${relative} provider enum is current`);
}

function containsExactEnum(value, expected) {
  if (Array.isArray(value)) return value.some((item) => containsExactEnum(item, expected));
  if (!value || typeof value !== "object") return false;
  if (
    Array.isArray(value.enum) &&
    value.enum.length === expected.length &&
    value.enum.every((item, index) => item === expected[index])
  ) {
    return true;
  }
  return Object.values(value).some((item) => containsExactEnum(item, expected));
}

function formatRust(contents) {
  const result = spawnSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], {
    input: contents,
    encoding: "utf8",
  });
  if (result.error || result.status !== 0 || typeof result.stdout !== "string") {
    throw new Error(
      `Could not format generated Rust catalog: ${result.error?.message ?? result.stderr ?? result.status}`,
    );
  }
  return result.stdout;
}

function validateCatalog(value) {
  if (
    !value ||
    value.schema_version !== 1 ||
    !Array.isArray(value.providers) ||
    value.providers.length === 0
  ) {
    throw new Error(`Invalid provider catalog at ${catalogPath}`);
  }
  const ids = new Set();
  const orders = new Set();
  for (const entry of value.providers) {
    if (
      !entry ||
      typeof entry.id !== "string" ||
      !/^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$/.test(entry.id) ||
      entry.id.length > 32
    ) {
      throw new Error("Provider catalog contains an invalid id");
    }
    if (ids.has(entry.id) || orders.has(entry.order)) {
      throw new Error(`Provider catalog contains duplicate id/order: ${entry.id}`);
    }
    ids.add(entry.id);
    orders.add(entry.order);
    if (!Array.isArray(entry.environment_keys) || !entry.credential_config) {
      // Ambient providers intentionally have no credential config, but still
      // must have an explicit null in the source file.
      if (entry.credential_config !== null) {
        throw new Error(`Provider ${entry.id} has invalid credential_config`);
      }
    }
    if (entry.credential_config !== null && entry.credential_config.kind !== "api_key") {
      throw new Error(`Provider ${entry.id} has an unsupported credential kind`);
    }
    if (entry.browser_session !== null) {
      const login = new URL(entry.browser_session.login_url);
      if (login.protocol !== "https:") {
        throw new Error(`Provider ${entry.id} browser-session login must use HTTPS`);
      }
      if (login.username || login.password || login.hash) {
        throw new Error(`Provider ${entry.id} browser-session login URL has forbidden components`);
      }
      if (!entry.browser_session.cookie_hosts.includes(login.hostname)) {
        throw new Error(`Provider ${entry.id} login host must be an exact cookie host`);
      }
      if (
        entry.browser_session.cookie_hosts.some(
          (host) => host !== host.toLowerCase() || host.endsWith("."),
        )
      ) {
        throw new Error(
          `Provider ${entry.id} browser-session hosts must be lowercase without trailing dots`,
        );
      }
      const supportedBrowsers = new Set([
        "safari",
        "chrome",
        "chromeBeta",
        "chromeCanary",
        "arc",
        "arcBeta",
        "arcCanary",
        "chatgptAtlas",
        "chromium",
        "yandex",
        "firefox",
        "firefoxBeta",
        "firefoxDeveloperEdition",
        "firefoxNightly",
        "zen",
        "brave",
        "braveBeta",
        "braveNightly",
        "edge",
        "edgeBeta",
        "edgeCanary",
        "helium",
        "vivaldi",
        "dia",
        "comet",
      ]);
      if (
        entry.browser_session.browser_priority.some((browser) => !supportedBrowsers.has(browser))
      ) {
        throw new Error(`Provider ${entry.id} has an unsupported SweetCookieKit browser id`);
      }
    }
  }
}

function rustIdent(id) {
  const conventional = {
    openrouter: "OpenRouter",
    deepseek: "DeepSeek",
    litellm: "LiteLlm",
  };
  if (conventional[id]) {
    return conventional[id];
  }
  const identifier = id
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
  return identifier === "Self" ? "SelfProvider" : identifier;
}

function rustString(value) {
  return JSON.stringify(value).replace(/\\u2028|\\u2029/g, (match) =>
    match === "\\u2028" ? "\\u{2028}" : "\\u{2029}",
  );
}

function escapeSwift(value) {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\u2028/g, "\\u{2028}")
    .replace(/\u2029/g, "\\u{2029}");
}

function swiftIdent(id) {
  return `\`${id}\``;
}
