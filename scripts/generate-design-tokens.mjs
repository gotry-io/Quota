#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
/**
 * Regenerate CSS, TypeScript, and Swift design-token adapters.
 *
 * `packages/design-tokens/tokens.json` is the only hand-edited source.
 */
import Ajv2020 from "ajv/dist/2020.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.slice(2).includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("Usage: generate-design-tokens.mjs [--check]");
}

const tokensPath = join(root, "packages/design-tokens/tokens.json");
const schemaPath = join(root, "packages/design-tokens/tokens.schema.json");
const tokens = JSON.parse(readFileSync(tokensPath, "utf8"));
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const validateSchema = new Ajv2020({ allErrors: true, strict: true }).compile(schema);
if (!validateSchema(tokens)) {
  const details = validateSchema.errors
    ?.map((error) => `${error.instancePath || "/"} ${error.message}`)
    .join("; ");
  throw new Error(`Design tokens do not match ${schemaPath}: ${details}`);
}
validateTokens(tokens);

const colorLeaves = collectColorLeaves(tokens.color);
const appleColor = tokens.overrides.apple.color;
const header = `Generated by scripts/generate-design-tokens.mjs — do not edit.
Source: packages/design-tokens/tokens.json`;

writeGenerated(
  "apps/web/src/lib/styles/tokens.generated.css",
  emitCss(colorLeaves, tokens.spacing, tokens.radius, header),
);
writeGenerated("apps/web/src/lib/tokens.generated.ts", emitTs(tokens.threshold, header));
writeGenerated(
  "packages/apple-shared/Sources/QuotaPresentation/DesignTokens.generated.swift",
  emitSwift(colorLeaves, appleColor, tokens.threshold, tokens.spacing, tokens.radius, header),
);

function writeGenerated(relative, contents) {
  const path = join(root, relative);
  if (checkOnly) {
    if (readFileSync(path, "utf8") !== contents) {
      throw new Error(`Generated file is out of date: ${relative}`);
    }
    console.log(`${relative} is current`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
  console.log(`wrote ${relative}`);
}

function validateTokens(value) {
  if (value.threshold.quota_warning_percent >= value.threshold.quota_healthy_percent) {
    throw new Error("quota_warning_percent must be below quota_healthy_percent");
  }
  const cssNames = new Set();
  for (const leaf of collectColorLeaves(value.color)) {
    for (const name of [...leaf.css, ...leaf.cssDark]) {
      if (cssNames.has(name)) {
        throw new Error(`Duplicate CSS custom property: ${name}`);
      }
      cssNames.add(name);
    }
  }
}

function collectColorLeaves(node, path = []) {
  if (node && typeof node.light === "string" && typeof node.dark === "string") {
    return [
      {
        path: path.join("."),
        ident: swiftIdent(path),
        light: node.light,
        dark: node.dark,
        css: node.css ?? [],
        cssDark: node.css_dark ?? [],
      },
    ];
  }
  if (!node || typeof node !== "object" || Array.isArray(node)) return [];
  return Object.entries(node).flatMap(([key, child]) => collectColorLeaves(child, [...path, key]));
}

function emitCss(leaves, spacing, radius, banner) {
  const lines = [`/* ${banner.split("\n").join("\n * ")} */`, "", ":root {"];
  for (const leaf of leaves) {
    const value = `light-dark(${leaf.light}, ${leaf.dark})`;
    for (const name of leaf.css) {
      lines.push(`  ${name}: ${value};`);
    }
    for (const name of leaf.cssDark) {
      lines.push(`  ${name}: ${leaf.dark};`);
    }
  }
  for (const size of spacing) {
    lines.push(`  --space-${size}: ${size}px;`);
  }
  for (const [name, size] of Object.entries(radius)) {
    lines.push(`  --radius-${name}: ${size}px;`);
  }
  lines.push("}", "");
  return `${lines.join("\n")}`;
}

function emitTs(threshold, banner) {
  return `// ${banner.split("\n").join("\n// ")}

export const QUOTA_HEALTHY_PERCENT = ${threshold.quota_healthy_percent};
export const QUOTA_WARNING_PERCENT = ${threshold.quota_warning_percent};
`;
}

function indentBlock(text, spaces) {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length === 0 ? line : pad + line))
    .join("\n");
}

function emitSwift(leaves, appleColor, threshold, spacing, radius, banner) {
  const appleRadius = { ...radius, ...tokens.overrides.apple.radius };
  const colorDecls = indentBlock(
    leaves
      .map((leaf) => {
        const resolved = resolveAppleAdaptive(leaf, appleColor);
        return `public static let ${leaf.ident} = AdaptiveRGB(
  light: ${swiftRgb(resolved.light)},
  dark: ${swiftRgb(resolved.dark)}
)`;
      })
      .join("\n\n"),
    4,
  );
  const systemDecls = indentBlock(
    appleSystemMappings(appleColor)
      .map((entry) => {
        const opacity =
          entry.opacity == null
            ? ""
            : `\npublic static let ${entry.ident}Opacity: Double = ${entry.opacity}`;
        return `public static let ${entry.ident} = "${escapeSwift(entry.system)}"${opacity}`;
      })
      .join("\n"),
    4,
  );
  const spacingDecls = indentBlock(
    spacing.map((size) => `public static let space${size}: Double = ${size}`).join("\n"),
    4,
  );
  const radiusDecls = indentBlock(
    Object.entries(appleRadius)
      .map(([name, size]) => `public static let ${name}: Double = ${size}`)
      .join("\n"),
    4,
  );
  return `// ${banner.split("\n").join("\n// ")}

import Foundation

public enum DesignTokens {
  public struct RGB: Sendable, Equatable {
    public let red: Double
    public let green: Double
    public let blue: Double

    public init(red: Double, green: Double, blue: Double) {
      self.red = red
      self.green = green
      self.blue = blue
    }
  }

  public struct AdaptiveRGB: Sendable, Equatable {
    public let light: RGB
    public let dark: RGB

    public init(light: RGB, dark: RGB) {
      self.light = light
      self.dark = dark
    }
  }

  public enum Color {
${colorDecls}
  }

  /// Apple system colour roles recorded in tokens.json. QuotaTheme / QuotaPalette map these;
  /// this file stays Foundation-only.
  public enum AppleSystemColor {
${systemDecls}
  }

  public enum Threshold {
    public static let quotaHealthyPercent: Double = ${threshold.quota_healthy_percent}
    public static let quotaWarningPercent: Double = ${threshold.quota_warning_percent}
  }

  public enum Spacing {
${spacingDecls}
  }

  public enum Radius {
${radiusDecls}
  }
}
`;
}

function resolveAppleAdaptive(leaf, appleColor) {
  const override = lookup(appleColor, leaf.path.split("."));
  return {
    light: resolveAppearance(override, "light") ?? leaf.light,
    dark: resolveAppearance(override, "dark") ?? leaf.dark,
  };
}

function resolveAppearance(override, appearance) {
  if (!override || typeof override !== "object") return null;
  if (typeof override[appearance] === "string") return override[appearance];
  return null;
}

function appleSystemMappings(appleColor, path = []) {
  if (appleColor && typeof appleColor.system === "string") {
    return [
      {
        ident: swiftIdent(path),
        system: appleColor.system,
        opacity: typeof appleColor.opacity === "number" ? appleColor.opacity : null,
      },
    ];
  }
  if (!appleColor || typeof appleColor !== "object" || Array.isArray(appleColor)) return [];
  const nested = Object.entries(appleColor).flatMap(([key, child]) => {
    if (key === "light" || key === "dark") {
      if (child && typeof child === "object" && typeof child.system === "string") {
        return [
          {
            ident: swiftIdent([...path, key]),
            system: child.system,
            opacity: typeof child.opacity === "number" ? child.opacity : null,
          },
        ];
      }
      return [];
    }
    return appleSystemMappings(child, [...path, key]);
  });
  return nested;
}

function lookup(node, parts) {
  let current = node;
  for (const part of parts) {
    if (!current || typeof current !== "object") return null;
    current = current[part];
  }
  return current ?? null;
}

function swiftIdent(path) {
  const words = path
    .join(" ")
    .replaceAll(".", " ")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  return words
    .map((word, index) => {
      if (/^\d+$/.test(word)) return word;
      const lower = word.toLowerCase();
      if (index === 0) return lower;
      return lower.charAt(0).toUpperCase() + lower.slice(1);
    })
    .join("");
}

function swiftRgb(hex) {
  const { red, green, blue } = parseHex(hex);
  return `RGB(red: ${red}.0 / 255.0, green: ${green}.0 / 255.0, blue: ${blue}.0 / 255.0)`;
}

function parseHex(hex) {
  const value = hex.replace("#", "");
  return {
    red: Number.parseInt(value.slice(0, 2), 16),
    green: Number.parseInt(value.slice(2, 4), 16),
    blue: Number.parseInt(value.slice(4, 6), 16),
  };
}

function escapeSwift(value) {
  return value.replaceAll("\\", "\\\\").replaceAll('"', '\\"');
}
