#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
/**
 * Regenerate language-specific plan display tables.
 *
 * `packages/protocol/catalog/plan-display.json` is the only hand-edited source.
 */
import Ajv2020 from "ajv/dist/2020.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.slice(2).includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("Usage: generate-plan-display.mjs [--check]");
}
const catalogPath = join(root, "packages/protocol/catalog/plan-display.json");
const schemaPath = join(root, "packages/protocol/catalog/plan-display.schema.json");
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const validateSchema = new Ajv2020({ allErrors: true, strict: true }).compile(schema);
if (!validateSchema(catalog)) {
  const details = validateSchema.errors
    ?.map((error) => `${error.instancePath || "/"} ${error.message}`)
    .join("; ");
  throw new Error(`Plan display catalog does not match ${schemaPath}: ${details}`);
}
validateCatalog(catalog);
const entries = Object.entries(catalog.plans);

const swiftEntries = entries
  .map(([key, displayName]) => `    "${escapeSwift(key)}": "${escapeSwift(displayName)}",`)
  .join("\n");
const tsEntries = entries
  .map(([key, displayName]) => {
    const ident = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
    return `  ${ident}: ${JSON.stringify(displayName)},`;
  })
  .join("\n");

const swift = `// Generated by scripts/generate-plan-display.mjs — do not edit.
// Source: packages/protocol/catalog/plan-display.json

extension PlanDisplay {
  /// Module-internal: the table is an implementation detail of \`displayName\`, and \`package\`
  /// is not visible when QuotaPresentation is built as another package's dependency.
  static let knownPlans: [String: String] = [
${swiftEntries}
  ]
}
`;
writeGenerated(
  "packages/apple-shared/Sources/QuotaPresentation/PlanDisplay.generated.swift",
  swift,
);

const ts = `// Generated by scripts/generate-plan-display.mjs — do not edit.
// Source: packages/protocol/catalog/plan-display.json

export const KNOWN_PLANS: Readonly<Record<string, string>> = {
${tsEntries}
};
`;
writeGenerated("apps/web/src/lib/plan-display.generated.ts", ts);

function writeGenerated(relative, contents) {
  const path = join(root, relative);
  if (checkOnly) {
    if (readFileSync(path, "utf8") !== contents) {
      throw new Error(`Generated file is out of date: ${relative}`);
    }
    console.log(`${relative} is current`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
  console.log(`wrote ${relative}`);
}

function validateCatalog(value) {
  if (!value || typeof value.plans !== "object" || value.plans === null) {
    throw new Error(`Invalid plan display catalog at ${catalogPath}`);
  }
  for (const [key, displayName] of Object.entries(value.plans)) {
    if (typeof key !== "string" || !/^[a-z0-9]+$/.test(key)) {
      throw new Error(`Plan display key must already have separators dropped: ${key}`);
    }
    if (typeof displayName !== "string" || displayName.trim() !== displayName || !displayName) {
      throw new Error(`Plan display name for ${key} must be non-empty trimmed text`);
    }
  }
}

function escapeSwift(value) {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\u2028/g, "\\u{2028}")
    .replace(/\u2029/g, "\\u{2029}");
}
