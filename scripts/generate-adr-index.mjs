#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
/**
 * Regenerate docs/decisions/README.md from ADR header metadata.
 *
 * Hand-edited source: the `- Status:`, `- Superseded by:`, and `- Amended:` lines in
 * `docs/decisions/NNNN-*.md`.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.slice(2).includes("--check");
if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("Usage: generate-adr-index.mjs [--check]");
}

const STATUSES = new Set(["Accepted", "Partially superseded", "Superseded"]);
const decisionsDir = join(root, "docs/decisions");
const files = readdirSync(decisionsDir)
  .filter((name) => /^\d{4}-.+\.md$/.test(name))
  .sort();
if (files.length === 0) {
  throw new Error(`No ADR files in ${decisionsDir}`);
}

const records = files.map((name) => parseAdr(name, readFileSync(join(decisionsDir, name), "utf8")));
const byNumber = new Map();
for (const record of records) {
  if (byNumber.has(record.number)) {
    throw new Error(`Duplicate ADR number ${record.number}`);
  }
  byNumber.set(record.number, record);
}
for (const record of records) {
  for (const target of record.supersededBy) {
    if (!byNumber.has(target)) {
      throw new Error(`${record.file}: Superseded by ${target}, which has no ADR file`);
    }
  }
}

const contents = renderIndex(records, byNumber);
writeGenerated("docs/decisions/README.md", contents);

function parseAdr(file, text) {
  const lines = text.split(/\r?\n/);
  const titleMatch = lines[0]?.match(/^# ADR (\d{4}): (.+)$/);
  if (!titleMatch) {
    throw new Error(`${file}: first line must be '# ADR NNNN: Title'`);
  }
  const number = titleMatch[1];
  const title = titleMatch[2].trim();
  const fileNumber = file.slice(0, 4);
  if (fileNumber !== number) {
    throw new Error(`${file}: filename number ${fileNumber} does not match title ${number}`);
  }

  let index = 1;
  while (index < lines.length && (lines[index].trim() === "" || lines[index].startsWith(">"))) {
    index += 1;
  }
  const bullets = [];
  while (index < lines.length && lines[index].startsWith("- ")) {
    let bullet = lines[index].slice(2);
    index += 1;
    while (
      index < lines.length &&
      /^[ \t]+\S/.test(lines[index]) &&
      !lines[index].startsWith("- ")
    ) {
      bullet += ` ${lines[index].trim()}`;
      index += 1;
    }
    bullets.push(bullet);
  }

  let status = null;
  const supersededBy = [];
  const amended = [];
  for (const bullet of bullets) {
    if (bullet.startsWith("Status:")) {
      const value = bullet.slice("Status:".length).trim();
      if (status !== null) {
        throw new Error(`${file}: multiple Status lines`);
      }
      if (!STATUSES.has(value)) {
        throw new Error(
          `${file}: Status must be Accepted | Partially superseded | Superseded (got ${JSON.stringify(value)})`,
        );
      }
      status = value;
    } else if (bullet.startsWith("Superseded by:")) {
      const value = bullet.slice("Superseded by:".length).trim();
      if (!value) {
        throw new Error(`${file}: empty Superseded by`);
      }
      for (const part of value.split(",").map((item) => item.trim())) {
        if (!/^\d{4}$/.test(part)) {
          throw new Error(
            `${file}: Superseded by must be NNNN[, NNNN] (got ${JSON.stringify(part)})`,
          );
        }
        supersededBy.push(part);
      }
    } else if (bullet.startsWith("Amended:")) {
      const rest = bullet.slice("Amended:".length).trim();
      const match = rest.match(/^(\d{4}-\d{2}-\d{2})\b/);
      if (!match) {
        throw new Error(`${file}: Amended must start with YYYY-MM-DD`);
      }
      amended.push(match[1]);
    }
  }
  if (!status) {
    throw new Error(`${file}: missing Status`);
  }
  if ((status === "Superseded" || status === "Partially superseded") && supersededBy.length === 0) {
    throw new Error(`${file}: ${status} requires Superseded by: NNNN`);
  }
  if (status === "Accepted" && supersededBy.length > 0) {
    throw new Error(`${file}: Accepted must not have Superseded by`);
  }
  return { file, number, title, status, supersededBy, amended: uniqueSorted(amended) };
}

function uniqueSorted(values) {
  return [...new Set(values)].sort();
}

function renderIndex(records, byNumber) {
  const rows = records.map((record) => {
    const superseded = record.supersededBy
      .map((number) => `[${number}](./${byNumber.get(number).file})`)
      .join(", ");
    const amended = record.amended.join(", ");
    return `| [${record.number}](./${record.file}) | ${escapeCell(record.title)} | ${record.status} | ${superseded} | ${amended} |`;
  });
  return `<!-- Generated by scripts/generate-adr-index.mjs — do not edit. -->
# Architecture decision records

Generated from the \`- Status:\`, \`- Superseded by:\`, and \`- Amended:\` lines in each
\`NNNN-*.md\` file in this directory. Do not edit this index by hand; run
\`pnpm generate:adr-index\`.

Status values: **Accepted** is current; **Partially superseded** remains a historical record with
later ADRs replacing named parts; **Superseded** is not a source of current implementation
instructions. Stable ADR URLs stay.

| ADR | Title | Status | Superseded by | Amended |
| --- | --- | --- | --- | --- |
${rows.join("\n")}
`;
}

function escapeCell(value) {
  return value.replaceAll("|", "\\|");
}

function writeGenerated(relative, contents) {
  const path = join(root, relative);
  if (checkOnly) {
    if (readFileSync(path, "utf8") !== contents) {
      throw new Error(`Generated file is out of date: ${relative}`);
    }
    console.log(`${relative} is current`);
    return;
  }
  writeFileSync(path, contents);
  console.log(`wrote ${relative}`);
}
