#!/usr/bin/env node
/**
 * Regenerates protocol ProviderId, Swift ProviderID, and JSON Schema provider enums
 * from packages/provider/src/catalog.ts.
 * Run: pnpm generate:provider-catalog
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

async function loadCatalog() {
  try {
    const mod = await import(join(root, "packages/provider/src/catalog.ts"));
    return mod.providerCatalogSnapshot();
  } catch (error) {
    console.error("Could not import catalog.ts (need Node type stripping):", error);
    process.exit(1);
  }
}

const catalog = await loadCatalog();
const ids = catalog.map((e) => e.id);
const idsLiteral = ids.map((id) => `"${id}"`).join(", ");
const enumJson = ids.map((id) => `"${id}"`).join(", ");

// --- protocol TS ---
const protocolTs = `// Generated by scripts/generate-provider-catalog.mjs — do not edit.
// Source: packages/provider/src/catalog.ts

import { z } from "zod";

export const PROVIDER_IDS = [${idsLiteral}] as const;
export type ProviderId = (typeof PROVIDER_IDS)[number];
export const ProviderIdSchema = z.enum(PROVIDER_IDS);
`;

const protocolOut = join(root, "packages/protocol/src/provider-ids.generated.ts");
mkdirSync(dirname(protocolOut), { recursive: true });
writeFileSync(protocolOut, protocolTs);
console.log(`wrote ${protocolOut}`);

// --- JSON Schema provider enums ---
for (const relative of [
  "packages/protocol/schema/quota-snapshot-v1.json",
  "packages/protocol/schema/quota-collection-report-v1.json",
]) {
  const path = join(root, relative);
  const original = readFileSync(path, "utf8");
  const updated = original.replace(
    /"provider":\s*\{\s*"enum":\s*\[[^\]]*\]\s*\}/,
    `"provider": { "enum": [${enumJson}] }`,
  );
  if (original.includes(`"enum": [${enumJson}]`)) {
    console.log(`${relative} provider enum already current`);
  } else if (updated === original) {
    console.warn(`warning: provider enum not found/updated in ${relative}`);
  } else {
    writeFileSync(path, updated);
    console.log(`wrote ${relative} provider enum`);
  }
}

// Runtime Zod already enforces snapshot.provider === result.provider.
// Keep JSON Schema to a simple provider enum (no per-id allOf bloat).
const reportPath = join(root, "packages/protocol/schema/quota-collection-report-v1.json");
const report = JSON.parse(readFileSync(reportPath, "utf8"));
if (report.$defs?.result?.allOf) {
  delete report.$defs.result.allOf;
  writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
  console.log("stripped collection-report provider allOf (enum-only)");
}

// --- Swift ---
const cases = ids.join("\n  case ");
const displayName = catalog
  .map((e) => `    case .${e.id}: "${escapeSwift(e.displayName)}"`)
  .join("\n");
const defaultVisible = catalog.map((e) => `    case .${e.id}: ${e.defaultVisible}`).join("\n");
const loginCommand = catalog
  .map((e) => `    case .${e.id}: "${escapeSwift(e.loginCommand)}"`)
  .join("\n");
const brandIcon = catalog
  .map((e) => `    case .${e.id}: "${escapeSwift(e.brandIconAsset)}"`)
  .join("\n");
const order = catalog.map((e) => `    case .${e.id}: ${e.order}`).join("\n");
const configurable = catalog
  .filter((e) => e.config !== null)
  .map((e) => `.${e.id}`)
  .join(", ");

const swift = `// Generated by scripts/generate-provider-catalog.mjs — do not edit.
// Source: packages/provider/src/catalog.ts

import Foundation

enum ProviderID: String, Codable, CaseIterable, Identifiable, Sendable {
  case ${cases}

  var id: String { rawValue }

  var displayName: String {
    switch self {
${displayName}
    }
  }

  /// Menubar Agents toggle default (catalog.defaultVisible).
  var defaultVisible: Bool {
    switch self {
${defaultVisible}
    }
  }

  /// Auth recovery command for Settings/Overview.
  var loginCommand: String {
    switch self {
${loginCommand}
    }
  }

  var brandIconAssetName: String {
    switch self {
${brandIcon}
    }
  }

  var sortOrder: Int {
    switch self {
${order}
    }
  }

  /// Providers that store secrets via quotacli config / Settings API key form.
  static var configurableCases: [ProviderID] {
    [${configurable}]
  }

  var isConfigurable: Bool {
    Self.configurableCases.contains(self)
  }
}
`;

const swiftOut = join(root, "apps/menubar/Sources/QuotaBar/Core/Models/ProviderID.generated.swift");
mkdirSync(dirname(swiftOut), { recursive: true });
writeFileSync(swiftOut, swift);
console.log(`wrote ${swiftOut} (${catalog.length} providers)`);

function escapeSwift(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}
